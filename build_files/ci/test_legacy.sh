#!/usr/bin/env bash
set -euo pipefail

blender=$1
script_dir=$(cd "$(dirname "$0")" && pwd)
work_dir=$(mktemp -d)
trap 'rm -rf "$work_dir"' EXIT

# Save test outputs beside the input copies so relative library paths still resolve.
cp -R "$script_dir/fixtures" "$work_dir/"
for version_dir in "$work_dir"/fixtures/*; do
    printf 'Checking legacy files generated by Blender %s\n' "${version_dir##*/}"
    for fixture in mesh modifier linked mixed; do
        "$blender" --background --factory-startup --python-exit-code 1 \
            --python "$script_dir/legacy_blend.py" -- "$version_dir" --case "$fixture"
    done
done
